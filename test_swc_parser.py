class SeededSelectionTests(unittest.TestCase):
    def test_empirical_growth_distribution_is_normalized_and_seedable(self):
        lengths, weights = parse_length_distribution()
        self.assertEqual(len(lengths), 533)
        self.assertEqual(len(weights), len(lengths))
        self.assertAlmostEqual(sum(weights), 1.0)
        first = select_length(lengths, weights, random.Random(91))
        second = select_length(lengths, weights, random.Random(91))
        self.assertEqual(first, second)
        self.assertIn(first, lengths)

    def test_seeded_selection_is_reproducible_uniform_and_without_replacement(self):
        options = list(range(1, 11))
        samples = {root: [[root]] for root in options}
        first, label = sample_random_dendrites(
            options, "all", samples, 0.3, random.Random(123)
        )
        second, _ = sample_random_dendrites(
            options, "all", samples, 0.3, random.Random(123)
        )
        self.assertEqual(first, [1, 2, 5])
        self.assertEqual(second, first)
        self.assertEqual(len(first), len(set(first)))
        self.assertIn("30%", label)

    def test_ratio_rounding_and_validation_are_explicit(self):
        options = [1, 2, 3, 4, 5]
        samples = {root: [[root]] for root in options}
        selected, _ = sample_random_dendrites(
            options, "all", samples, 0.5, random.Random(5)
        )
        self.assertEqual(len(selected), 3)
        self.assertEqual(sample_random_dendrites(options, "all", samples, 0)[0], [])
        self.assertEqual(
            sample_random_dendrites(options, "all", samples, 1, random.Random(1))[0],
            options,
        )
        for invalid in (-0.01, 1.01):
            with self.subTest(ratio=invalid), self.assertRaises(ValueError):
                sample_random_dendrites(options, "all", samples, invalid)


class RemodelingInvariantTests(unittest.TestCase):
    def test_terminal_shrink_is_exact_and_does_not_move_other_samples(self):
        before, after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY, [4], "shrink", 50.0
        )
        self.assertAlmostEqual(after[LENGTHS][4], before[LENGTHS][4] * 0.5)
        self.assertAlmostEqual(
            total_dendritic_length(after),
            total_dendritic_length(before) - before[LENGTHS][4] * 0.5,
        )
        for sample_id in (1, 2, 3, 5, 6, 7):
            self.assertEqual(after[SAMPLES][sample_id], before[SAMPLES][sample_id])

    def test_shrink_retains_the_crossed_cylindrical_edge_radius(self):
        morphology = """\
1 1 0 0 0 10 -1
2 3 2 0 0 1 1
"""
        _before, after, _lines, _roots, _samples = remodel(
            morphology, [2], "shrink", 50.0
        )
        self.assertAlmostEqual(after[SAMPLES][2][5], 1.0)
        self.assertAlmostEqual(after[LENGTHS][2], 1.0)
        self.assertAlmostEqual(sum(after[AREAS].values()), 2.0 * pi)
        self.assertAlmostEqual(total_dendritic_volume(after), pi)

    def test_nonterminal_shrink_translates_descendants_rigidly(self):
        before, after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY, [2], "shrink", 25.0
        )
        self.assertAlmostEqual(after[LENGTHS][2], 1.5)
        self.assertAlmostEqual(after[LENGTHS][4], before[LENGTHS][4])
        self.assertAlmostEqual(after[LENGTHS][5], before[LENGTHS][5])
        for child in (4, 5):
            before_vector = np.asarray(before[SAMPLES][child][2:5]) - np.asarray(
                before[SAMPLES][3][2:5]
            )
            after_vector = np.asarray(after[SAMPLES][child][2:5]) - np.asarray(
                after[SAMPLES][3][2:5]
            )
            np.testing.assert_allclose(after_vector, before_vector)

    def test_remove_deletes_the_complete_subtree_without_orphans(self):
        _before, after, _lines, _roots, _samples = remodel(Y_MORPHOLOGY, [2], "remove")
        self.assertEqual(set(after[SAMPLES]), {1, 6, 7})
        self.assertEqual(after[DENDRITE_ROOTS], [6])
        self.assertEqual(after[TERMINALS], [6])
        for sample in after[SAMPLES].values():
            self.assertTrue(int(sample[6]) == -1 or int(sample[6]) in after[SAMPLES])

    def test_nonterminal_extend_adds_exact_length_and_preserves_distal_geometry(self):
        before, after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY, [2], "extend", 1.0, "micrometers", seed=31
        )
        self.assertAlmostEqual(
            total_dendritic_length(after), total_dendritic_length(before) + 1.0
        )
        self.assertAlmostEqual(after[LENGTHS][2], before[LENGTHS][2] + 1.0)
        self.assertAlmostEqual(after[LENGTHS][4], before[LENGTHS][4])
        self.assertAlmostEqual(after[LENGTHS][5], before[LENGTHS][5])
        new_ids = set(after[SAMPLES]) - set(before[SAMPLES])
        self.assertTrue(new_ids)
        self.assertTrue(new_ids.issubset(after[SAMPLE_IDS_BY_SEGMENT][2]))
        new_tip = int(after[SAMPLES][4][6])
        self.assertIn(new_tip, new_ids)
        self.assertEqual(int(after[SAMPLES][4][6]), new_tip)
        self.assertEqual(int(after[SAMPLES][5][6]), new_tip)

    def test_branch_adds_two_daughters_of_the_requested_length(self):
        before, after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY, [4], "branch", 50.0, seed=41
        )
        target_length = before[LENGTHS][4] * 0.5
        daughters = sorted(
            sample_id
            for sample_id, sample in after[SAMPLES].items()
            if int(sample[6]) == 4
        )
        self.assertEqual(len(daughters), 2)
        self.assertEqual(len(after[BRANCH_POINTS]), len(before[BRANCH_POINTS]) + 1)
        self.assertEqual(len(after[DENDRITE_ROOTS]), len(before[DENDRITE_ROOTS]) + 2)
        self.assertEqual(len(after[TERMINALS]), len(before[TERMINALS]) + 1)
        for daughter in daughters:
            self.assertAlmostEqual(after[LENGTHS][daughter], target_length)
        self.assertAlmostEqual(
            total_dendritic_length(after),
            total_dendritic_length(before) + 2.0 * target_length,
        )

    def test_tiny_representable_extension_is_not_silently_ignored(self):
        before, after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY, [4], "extend", 1e-11, "micrometers", seed=43
        )
        added = total_dendritic_length(after) - total_dendritic_length(before)
        self.assertAlmostEqual(added, 1e-11, delta=1e-13)

    def test_scale_changes_all_selected_linear_dimensions_by_one_factor(self):
        before = parse_text(Y_MORPHOLOGY)
        before_roots = list(before[DENDRITE_ROOTS])
        _before, after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY, before_roots, "scale", 200.0
        )
        self.assertAlmostEqual(
            total_dendritic_length(after), 2.0 * total_dendritic_length(before)
        )
        self.assertAlmostEqual(
            sum(after[AREAS].values()), 4.0 * sum(before[AREAS].values())
        )
        self.assertAlmostEqual(
            total_dendritic_volume(after), 8.0 * total_dendritic_volume(before)
        )
        for root in before_roots:
            self.assertAlmostEqual(after[LENGTHS][root], 2.0 * before[LENGTHS][root])
        for sample_id, sample in before[SAMPLES].items():
            if int(sample[1]) in {3, 4}:
                np.testing.assert_allclose(
                    after[SAMPLES][sample_id][2:5],
                    2.0 * np.asarray(sample[2:5], dtype=float),
                )
                self.assertAlmostEqual(after[SAMPLES][sample_id][5], 2.0 * sample[5])
        self.assertEqual(after[SAMPLES][1], before[SAMPLES][1])

    def test_scale_can_target_one_region_without_changing_the_other(self):
        before = parse_text(Y_MORPHOLOGY)
        _before, after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY, before[BASAL], "scale", 150.0
        )
        for root in before[BASAL]:
            self.assertAlmostEqual(after[LENGTHS][root], 1.5 * before[LENGTHS][root])
        for root in before[APICAL]:
            self.assertAlmostEqual(after[LENGTHS][root], before[LENGTHS][root])
            for sample_id in before[SAMPLE_IDS_BY_SEGMENT][root]:
                self.assertEqual(after[SAMPLES][sample_id], before[SAMPLES][sample_id])

    def test_radius_change_supports_percent_and_absolute_units(self):
        before, percent_after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY,
            [4],
            "none",
            radius_change=50.0,
            radius_unit="percent",
        )
        self.assertAlmostEqual(percent_after[SAMPLES][4][5], 0.75)
        self.assertEqual(percent_after[SAMPLES][5], before[SAMPLES][5])

        _before, absolute_after, _lines, _roots, _samples = remodel(
            Y_MORPHOLOGY,
            [4],
            "none",
            radius_change=-0.1,
            radius_unit="micrometers",
        )
        self.assertAlmostEqual(absolute_after[SAMPLES][4][5], 0.4)

    def test_invalid_actions_fail_instead_of_emitting_invalid_geometry(self):
        with self.assertRaisesRegex(ValueError, "entire segment"):
            remodel(Y_MORPHOLOGY, [4], "shrink", 100.0)
        with self.assertRaisesRegex(ValueError, "non-positive radius"):
            remodel(
                Y_MORPHOLOGY,
                [4],
                "none",
                radius_change=-0.5,
                radius_unit="micrometers",
            )
        with self.assertRaisesRegex(ValueError, "more than 100000 samples"):
            remodel(
                Y_MORPHOLOGY,
                [4],
                "extend",
                1e20,
                "micrometers",
            )
        overflowing = """\
1 1 0 0 0 1 -1
2 3 1e200 0 0 0.5 1
"""
        with self.assertRaisesRegex(ValueError, "scale exceeds finite numeric range"):
            remodel(overflowing, [2], "scale", 1e200)



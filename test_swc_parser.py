class ShollGeometryTests(unittest.TestCase):
    def setUp(self):
        self.parsed = parse_text(CHORD_MORPHOLOGY)

    def test_line_sphere_intersections_count_outward_and_inward_crossings(self):
        intersections = sholl_intersections(
            self.parsed[SAMPLES],
            self.parsed[PARENTS],
            self.parsed[SOMA_SAMPLES],
            5.0,
            {3},
        )
        self.assertEqual(intersections, {5: 3, 10: 3, 15: 2})

    def test_shell_lengths_are_exact_and_conserve_total_length(self):
        lengths = sholl_length(
            self.parsed[SAMPLES],
            self.parsed[PARENTS],
            self.parsed[SOMA_SAMPLES],
            5.0,
            {3},
        )
        self.assertEqual(set(lengths), {5, 10, 15})
        for value in lengths.values():
            self.assertAlmostEqual(value, 15.0)
        self.assertAlmostEqual(sum(lengths.values()), 45.0)

    def test_fractional_shell_step_retains_exact_boundaries_and_length(self):
        lengths = sholl_length(
            self.parsed[SAMPLES],
            self.parsed[PARENTS],
            self.parsed[SOMA_SAMPLES],
            2.5,
            {3},
        )
        expected_bounds = {2.5, 5.0, 7.5, 10.0, 12.5, 15.0}
        self.assertEqual(set(lengths), expected_bounds)
        for value in lengths.values():
            self.assertAlmostEqual(value, 7.5)
        self.assertAlmostEqual(sum(lengths.values()), 45.0)

    def test_branch_points_are_assigned_to_one_shell(self):
        parsed = parse_text(Y_MORPHOLOGY)
        values = sholl_branch_points(
            parsed[BRANCH_POINTS],
            parsed[SAMPLES],
            parsed[SOMA_SAMPLES],
            1.0,
        )
        self.assertEqual(values, {1: 0, 2: 1})
        self.assertEqual(sum(values.values()), 1)

    def test_near_tangent_secant_is_not_collapsed_to_one_contact(self):
        for label, height, expected in (
            ("near tangent", 0.9999999, 3),
            ("exact tangent", 1.0, 2),
        ):
            morphology = f"""\
1 1 0 0 0 0.5 -1
2 3 -0.001 {height} 0 0.5 1
3 3 0.001 {height} 0 0.5 2
"""
            parsed = parse_text(morphology)
            values = sholl_intersections(
                parsed[SAMPLES],
                parsed[PARENTS],
                parsed[SOMA_SAMPLES],
                1.0,
                {3},
            )
            with self.subTest(label=label):
                self.assertEqual(values[1], expected)

    def test_impractically_small_step_is_rejected_before_allocation(self):
        with self.assertRaisesRegex(ValueError, "more than 10000 radial bins"):
            sholl_length(
                self.parsed[SAMPLES],
                self.parsed[PARENTS],
                self.parsed[SOMA_SAMPLES],
                1e-6,
                {3},
            )



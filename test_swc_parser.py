class CommandLineIntegrationTests(unittest.TestCase):
    def run_cli(self, *arguments: str, expected_status: int = 0):
        completed = subprocess.run(
            [sys.executable, str(REPOSITORY / "remod_cli.py"), *arguments],
            cwd=REPOSITORY,
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(
            completed.returncode,
            expected_status,
            msg=f"stdout:\n{completed.stdout}\nstderr:\n{completed.stderr}",
        )
        return completed

    def test_analysis_writes_deterministic_single_and_aggregate_json(self):
        with tempfile.TemporaryDirectory() as directory_name:
            directory = Path(directory_name)
            (directory / "a.swc").write_text(Y_MORPHOLOGY, encoding="utf-8")
            (directory / "b.swc").write_text(Y_MORPHOLOGY, encoding="utf-8")
            self.run_cli(
                "analyze",
                str(directory),
                "b.swc,a.swc",
                "--sholl-step",
                "2.5",
            )

            statistics = directory / "downloads" / "statistics"
            results = json.loads((statistics / "results.json").read_text())
            summary = json.loads((statistics / "summary.json").read_text())
            self.assertEqual(list(results), ["a.swc", "b.swc"])
            self.assertEqual(summary["file_count"], 2)
            self.assertEqual(summary["files"], ["a.swc", "b.swc"])
            length = summary["scalar_metrics"]["all_total_length"]
            self.assertAlmostEqual(length["mean"], 4.0 + 2.0 * sqrt(2.0))
            self.assertEqual(length["standard_deviation"], 0.0)

